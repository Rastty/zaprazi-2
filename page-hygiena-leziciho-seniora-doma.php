  <section id="plan-hygieny-na-luzku" class="zp-section"><div class="zp-wrap">
    <p class="zp-kicker">Orientační denní postup · jen při bezpečném zacházení</p>
    <h2 class="zp-section-title">Sedm kroků hygieny na lůžku, které rodině usnadní práci</h2>
    <p>Následující kroky řeší organizaci a šetrnou očistu dostupných částí těla. <strong>Nejsou návodem na vlastní otáčení, zvedání nebo ošetřování ran.</strong> Při potřebě celkové hygieny nesoběstačného člověka se nechte zaučit domácí sestrou.</p>
    <ol class="zp-guide-steps">
      <li><strong>Zeptejte se, co člověk potřebuje a zvládne.</strong> Zajistěte souhlas, soukromí, přiměřené osvětlení a dostatečně teplou místnost. Pokud může bezpečně umýt obličej či ruce sám, dejte mu prostor.</li>
      <li><strong>Vše připravte na dosah.</strong> Jemný neparfémovaný mycí přípravek podle snášenlivosti, čisté žínky, teplou vodu nebo vhodný bezoplachový prostředek, savé ručníky, vhodnou ochranu lůžka, suché prádlo, pytel na odpad a případně jednorázové rukavice při kontaktu s tělesnými tekutinami.</li>
      <li><strong>Udržujte bezpečnou polohu.</strong> Nastavte výšku lůžka pro pečujícího, pokud to vybavení umožňuje, a nenechávejte člověka v poloze proti jeho zdravotním doporučením. Pokud by bylo nutné nebezpečné otáčení nebo přenášení váhy, zastavte a požádejte o pomoc.</li>
      <li><strong>Očistěte dostupné části jemně a po menších úsecích.</strong> Začněte podle přání obličejem, rukama nebo podpažím. Použijte čisté pomůcky; pro intimní partie oddělenou žínku nebo jednorázový materiál. Mycí prostředek používejte podle návodu, bez zbytečného drhnutí.</li>
      <li><strong>Po očištění místo pečlivě osušte.</strong> Zejména kožní záhyby a oblasti vystavené vlhkosti. Kůži netřete silou. Ochranný či hydratační přípravek používejte podle doporučení a určení výrobku, nikoli na otevřené rány naslepo.</li>
      <li><strong>Zkontrolujte suché a hladké lůžko.</strong> Převlečte mokré či znečištěné textilie, vyhlaďte nepříjemné záhyby. Nepřidávejte vrstvy nepropustných podložek bez rozmyslu: mohou zvyšovat vlhkost, teplo či tlak a ovlivnit funkci matrace.</li>
      <li><strong>Ověřte pohodlí, únavu a další potřeby.</strong> Zeptejte se, zda něco nebolí nebo neštípe, nabídněte návrat do individuálně schválené polohy a zajistěte dostupné přivolání pomoci. Při novém kožním problému kontaktujte zdravotníka.</li>
