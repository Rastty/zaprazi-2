    <p class="zp-kicker">Otázky, které rodiny opravdu řeší</p>
    <h2 class="zp-section-title">Časté dotazy k domácí hygieně ležícího člověka</h2>
    <details><summary>Musí se ležící senior každý den celý umýt?</summary><p>Neexistuje jeden univerzální režim pro každého člověka. Pravidelná očista obličeje, rukou a intimních oblastí je důležitá, úplné mytí se přizpůsobuje potřebě, komfortu, pokožce a možnostem bezpečné péče. U člověka vyčerpaného hygienou pomůže individuální plán s pečujícími.</p></details>
    <details><summary>Je při mytí na lůžku lepší voda, nebo bezoplachový prostředek?</summary><p>Záleží na situaci, snášenlivosti pokožky a bezpečné manipulaci s vodou. Bezoplachový výrobek může být praktický, pokud je pro danou oblast určen, nevyžaduje oplach a člověku vyhovuje. Znečištění či zdravotní problémy mohou vyžadovat jiný postup.</p></details>
    <details><summary>Může rodina sama otáčet člověka během celkové hygieny?</summary><p>Ne vždy. Riziko pádu, poranění kůže nebo zad pečujícího závisí na schopnostech člověka a vybavení. Pokud není bezpečný postup nacvičený, nezkoušejte silové otáčení a domluvte zaučení či pomoc.</p></details>
    <details><summary>Jak předejít opruzeninám při používání plen?</summary><p>Včas vyměňujte znečištěnou pomůcku, jemně omyjte a důkladně osušte pokožku a ověřte správnou velikost. Ochranný přípravek může doporučit zdravotník podle stavu kůže. Při přetrvávajícím zarudnutí nebo mokvání jej kontaktujte.</p></details>
    <details><summary>Jak poznat, že jde možná o proleženinu?</summary><p>Varovným příznakem je změna barvy, místní teplo, zatvrdnutí, bolest, puchýř nebo rána zejména u kostních výčnělků. Při podezření potřebuje člověk odborné posouzení a bezpečné odlehčení; při horečce či výrazné bolesti nečekejte.</p></details>
    <details><summary>Má smysl kvůli hygieně kupovat drahou polohovací postel?</summary><p>Ne automaticky. Nejdřív je potřeba určit, zda je problém v poloze, přístupu, manipulaci nebo samostatnosti. O vhodnosti lůžka a matrace rozhodují individuální požadavky a ověřené parametry, nikoli samotné označení „pro seniory“.</p></details>
