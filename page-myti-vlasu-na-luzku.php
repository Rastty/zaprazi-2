    <h2 class="zp-section-title">Mytí vlasů na lůžku krok za krokem</h2>
    <ol class="zp-guide-steps">
      <li><strong>Vysvětlete, co budete dělat.</strong> Zeptejte se na souhlas, přání a citlivost pokožky. Zajistěte soukromí a teplou místnost.</li>
      <li><strong>Připravte pomůcky na dosah.</strong> Nepropustná savá podložka, vanička dle návodu, voda vhodné teploty, šampon, nádoba k oplachu, ručníky, hřeben a prostředky pro bezpečné vysušení.</li>
      <li><strong>Zkontrolujte podložení a odtok.</strong> Chraňte matraci, ověřte stabilitu nádoby na odpadní vodu a zkoušku odtoku bez člověka. Zkontrolujte teplotu vody a podle možností se zeptejte na její příjemnost.</li>
      <li><strong>Dodržte bezpečnou polohu hlavy.</strong> Nevynucujte záklon ani přesun, který člověk nezvládá. Pokud položení do vaničky vyžaduje rizikové zvedání, přerušte přípravu a požádejte o pomoc.</li>
      <li><strong>Šetrně umyjte a opláchněte.</strong> Jen při stabilní poloze použijte přiměřené množství vody, chraňte oči, uši a obličej. Nesměřujte proud k ústům nebo nosu.</li>
      <li><strong>Odsušte a upravte vlasy.</strong> Šampon pečlivě odstraňte, pokožku a vlasy osušte; bezpečně odstraňte mokré pomůcky a zajistěte čisté suché lůžkoviny.</li>
      <li><strong>Ověřte pohodlí a únavu.</strong> Upravte lůžko do původně schválené polohy, zeptejte se na komfort, zkontrolujte suchou pokožku a nechte na dosah přivolání pomoci.</li>
    </ol>
