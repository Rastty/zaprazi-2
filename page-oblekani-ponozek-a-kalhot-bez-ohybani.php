  <section id="postup-ponozky" class="zp-section"><div class="zp-wrap">
    <p class="zp-kicker">Prakticky · běžné ponožky</p>
    <h2 class="zp-section-title">Jak používat navlékač ponožek se šňůrami?</h2>
    <p>Jen pokud člověk sedí bezpečně a zvolenou pomůcku umí ovládat bez porušení individuálních pohybových omezení. Konkrétní výrobek se může lišit — <strong>jeho návod má přednost před tímto obecným postupem</strong>.</p>
    <ol class="zp-guide-steps">
      <li><strong>Připravte stabilní místo.</strong> Vhodně vysoká pevná židle s oporou, neklouzavá podlaha, volná cesta pro nohy, všechny věci v dosahu. Nezaklánějte se, abyste zachytili spadlý předmět.</li>
      <li><strong>Navlečte běžnou ponožku na tělo pomůcky.</strong> Ponožku rozprostřete podle návodu až k přednímu okraji. Pokud kvůli přípravě musíte do zakázaného předklonu nebo nelze ponožku nasadit rukama, požádejte o pomoc.</li>
      <li><strong>Položte navlékač před nohu.</strong> Držte obě dlouhé šňůry či pásky. Pohybem chodidla do otvoru pokračujte jen v rozsahu dovoleném vaší rehabilitací; nesnažte se nohu silou tlačit.</li>
      <li><strong>Rovnoměrně táhněte za pásky.</strong> Ponožka se vytahuje přes patu, pomůcka se uvolní. Zkontrolujte, že ponožka netlačí, nehrne se a nezachycuje za kůži. Pokud postup nejde, nezkoušejte prudké škubání.</li>
    </ol>
    <p class="zp-muted-copy">Podkladem obecné mechaniky je český návod navlékače SANOMED a edukace nemocnice AGEL. Netýká se automaticky kompresních punčoch, pro které se používají odlišné výrobky a postupy.</p>
