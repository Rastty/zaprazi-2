    <details><summary>Jak je to s ponožkami při otoku nohou?</summary><p>Ponožka nesmí nepřiměřeně škrtit. Při novém, náhle vzniklém nebo bolestivém otoku, poranění či změně zbarvení nejdřív kontaktujte zdravotníka, nikoli jen větší pomůcku.</p></details>
