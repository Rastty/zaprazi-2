    <h2 class="zp-section-title">Co je potřeba si vyjasnit?</h2>
    <details><summary>Pomůže navlékač ponožek každému po operaci kyčle?</summary><p>Ne. Má smysl jen tehdy, když člověk dokáže bezpečně sedět, připravit ponožku, ovládat pásky a dodržet individuální pohybový režim. O vhodnosti a nácviku rozhoduje jeho ošetřující tým.</p></details>
