      <li><strong>Pomocí podavače uchopte pas kalhot.</strong> Volnější střih se snadněji zachytává; předem vyzkoušejte, zda podavač látku spolehlivě drží.</li>
      <li><strong>Spusťte oděv k chodidlům a provlečte nohy.</strong> U některých pooperačních postupů se jako první obléká operovaná noha; nepovažujte to za pravidlo pro každého bez doporučení terapeutů.</li>
      <li><strong>Vsedě posuňte látku co nejvýš bezpečným způsobem.</strong> Nepřetahujte ji násilně a nezkoušejte prudké předklony nebo rotace.</li>
      <li><strong>Dotažení do pasu řešte jen při bezpečném postoji.</strong> Pokud musíte pustit chodítko, stát na jedné noze nebo ztrácíte rovnováhu, činnost přerušte a vyžádejte si individuální nácvik či pomoc.</li>
