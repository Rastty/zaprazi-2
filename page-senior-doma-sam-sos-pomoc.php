  <section id="faq-sos-senior" class="zp-section zp-section-soft">
    <div class="zp-wrap zp-faq">
      <p class="zp-kicker">Časté otázky</p><h2 class="zp-section-title">Co rodiny před pořízením SOS zařízení často neví?</h2>
      <details><summary>Stačí SOS tlačítko na mobilu?</summary><p>Jen pokud ho člověk bude mít u sebe, dokáže ho ovládat a někdo skutečně převezme poplach. Telefon neřeší automaticky situaci, kdy je vybitý nebo když rodina není dostupná.</p></details>
      <details><summary>Je detekce pádu stoprocentně spolehlivá?</summary><p>Ne. Závisí na typu zařízení, způsobu nošení a algoritmu. Některé pády nemusejí být rozpoznány, některé běžné pohyby mohou způsobit falešný poplach. Nechte si limity písemně vysvětlit.</p></details>
      <details><summary>Musí senior nosit SOS přívěsek i do koupelny?</summary><p>Právě při sprchování nebo cestě na WC může být pomoc potřeba. Ověřte konkrétní voděodolnost výrobku, dosah a bezpečný způsob nošení. Ne každý přívěsek je určený k ponoření či sprchování.</p></details>
      <details><summary>Jaký je rozdíl mezi tlačítkem pro rodinu a tísňovou péčí?</summary><p>Rodinné řešení obvykle volá přednastavené kontakty. Registrovaná tísňová péče zahrnuje nepřetržitou komunikaci a zprostředkování pomoci podle smluvených pravidel; nejde pouze o technický výrobek.</p></details>
      <details><summary>Kolik stojí SOS hodinky nebo tísňová péče?</summary><p>Liší se nákup nebo pronájem zařízení, instalační poplatky, SIM, paušál, reakční služba a případné výjezdy. Bez aktuální smlouvy a nabídky nelze dát spolehlivou univerzální částku ani příslib úhrady.</p></details>
      <details><summary>Co když senior nechce zařízení nosit?</summary><p>Vysvětlete jeho přínos bez nátlaku a nechte člověka vyzkoušet skutečné používání. Pokud nošení odmítá nebo nezvládá, mohou po individuálním posouzení dávat větší smysl jiné formy podpory, pravidelný kontakt a úprava domácnosti.</p></details>
