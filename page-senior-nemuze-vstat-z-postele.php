        <article class="zp-decision-card">
          <h3>Hrazda nad postelí s úchytem</h3>
          <p>U některých lůžek slouží pro přesun a polohování v lehu nebo přitažení horní části těla. <strong>Visící úchyt není pevné boční madlo pro bezpečné postavení</strong>; použití závisí na schopnostech člověka, konstrukci hrazdy a pokynech výrobce či odborníka.</p>
          <p>Nelze ji automaticky doporučit člověku, který nedokáže držet úchop, potřebuje fyzické zvedání nebo má omezení po operaci.</p>
        </article>
        <article class="zp-decision-card">
          <h3>Postelová zábrana proti pádu</h3>
          <p>Má jiný účel než madlo pro mobilitu. Některé zábrany nejsou určené k zatížení při vstávání. Špatné rozměry, umístění, matrace či zmatenost člověka mohou zvýšit riziko zaklínění nebo pádu při přelézání.</p>
          <p><strong>Nutné:</strong> individuální posouzení rizik, kontrola kompatibility přesného lůžka a matrace a bezpečná montáž podle návodu výrobce.</p>
        </article>
        <article class="zp-decision-card">
          <h3>Výškově nastavitelná polohovací postel</h3>
          <p>Má smysl ji prověřit, když problém zahrnuje výšku lůžka, pravidelné polohování nebo náročnější péči. Ani elektricky nastavitelná postel však sama nezaručuje bezpečný přesun do stoje nebo dostatečnou stabilitu.</p>
