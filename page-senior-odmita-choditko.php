  <section id="faq-odmitani-choditka" class="zp-section zp-section-soft">
    <div class="zp-wrap zp-faq">
      <p class="zp-kicker">Časté otázky rodin</p>
      <h2 class="zp-section-title">Co když chodítko odmítá i po rozhovoru?</h2>
      <details><summary>Má smysl chodítko koupit jako překvapení?</summary><p>Obvykle ne. Člověk může pomůcku odmítnout nebo ji používat nesprávně. Vhodný typ, nastavení a nácvik je lepší řešit společně a s odborníkem.</p></details>
      <details><summary>Jak přesvědčit seniora, který se za chodítko stydí?</summary><p>Neslibujte zázračnou změnu. Ptejte se, co je pro něj důležité a jaký pohyb chce zachovat; respektujte jeho volbu. Pokud chce, může si pomůcku s odborníkem vyzkoušet bez závazku nákupu.</p></details>
      <details><summary>Je hůl lepší, když chodítko nechce?</summary><p>Ne automaticky. Hůl obvykle poskytuje jinou úroveň opory. O vhodnosti pro konkrétní chůzi rozhoduje posouzení, nikoli preference rodiny nebo samotný vzhled.</p></details>
      <details><summary>Co když s chodítkem zakopává nebo se předklání?</summary><p>Používání přerušte, pokud je nebezpečné, a nechte zkontrolovat výšku, typ, způsob chůze a překážky. Špatně zvolená nebo používaná pomůcka může stabilitu zhoršit.</p></details>
      <details><summary>Máme na něm trvat, když už jednou spadl?</summary><p>Po pádu nejdřív ověřte zranění a příčiny. Samotné nasazení chodítka není univerzální prevence dalších pádů. Odborník může doporučit i úpravu domácnosti nebo jinou intervenci.</p></details>
      <details><summary>Co když odmítá i návštěvu fyzioterapeuta?</summary><p>Zeptejte se, čeho se obává. Navrhněte nezávazné společné probrání konkrétní potíže s důvěryhodným lékařem. Při akutním ohrožení ale nečekejte na souhlas s běžnou kontrolou a volejte záchrannou službu.</p></details>
