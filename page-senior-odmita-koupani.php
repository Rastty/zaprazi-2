  <section id="faq-odmitani-hygieny" class="zp-section">
    <div class="zp-wrap zp-faq">
      <p class="zp-kicker">Časté otázky</p>
      <h2 class="zp-section-title">Co rodiny často potřebují vědět?</h2>
      <details><summary>Jak přimět seniora ke koupání, když odmítá?</summary><p>Netlačte na něj. Zjistěte důvod, nabídněte soukromí a příjemnější způsob očisty. Pokud se objevuje bolest, změna chování či hygienické zdravotní komplikace, poraďte se s lékařem nebo domácí péčí.</p></details>
      <details><summary>Musí se senior sprchovat každý den?</summary><p>Neexistuje jedna univerzální frekvence sprchování pro všechny. Důležitá je dostatečná individuální očista, zejména po znečištění, péče o citlivou pokožku a řešení zdravotních problémů. S plánem může pomoci sestra nebo lékař.</p></details>
      <details><summary>Co když člověk s demencí odmítá hygienu?</summary><p>Dementní onemocnění může ovlivnit porozumění postupu či vnímání potřeby mytí. Pomáhá klidný hlas, jednoduché kroky, respekt k osobnímu prostoru a známá rutina. Tento článek neurčuje diagnózu.</p></details>
      <details><summary>Je sprchovací židle vhodná pro každého?</summary><p>Ne. Musí být bezpečný přesun, vhodný typ a prostor, stabilní podlaha a ověřená nosnost. Pokud člověk neumí bezpečně usednout ani s běžnou pomocí, je nejdřív nutné odborné posouzení.</p></details>
      <details><summary>Pomůže přísavné madlo, když se senior bojí pádu?</summary><p>Ne jako automatická nosná opora pro přenášení váhy. U nosného madla je nezbytné ověřit způsob kotvení a podklad. Vhodnost konkrétního řešení posuzujte podle přesunu a návodu výrobce.</p></details>
      <details><summary>Co dělat, když očistu doma opakovaně nezvládáme?</summary><p>Proberte potíže s praktickým lékařem, domácí sestrou nebo sociálním pracovníkem. Pečovatelská služba může pomoci s osobní hygienou podle své nabídky a dostupnosti. Nenechávejte dlouhodobý kožní problém bez řešení.</p></details>
